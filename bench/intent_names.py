"""Builds src/undercurrent/text/intent_words/names_en.txt from the raw items in ClickHouse.

The intent extractor only counts things written like names. Lowercase writers and the
first word of a sentence say nothing about that, so a word also counts as a name when
the corpus usually capitalizes it in the middle of a sentence: "reddit", "spotify",
"youtube" do, "notion", "windows", "teams" don't (there only a capital letter makes them
a name), "friend" or "yellow" never.

Read-only. Run it against the live database (items keep 48 hours of text):

    uv run python bench/intent_names.py [--min-items 5] [--min-share 0.5]
"""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path

from dotenv import load_dotenv

from undercurrent.config import Env
from undercurrent.store import connect
from undercurrent.text.intents import (
    _HARD_BREAK,
    _TOKEN,
    CAPITALS,
    _case,
    boundary_words,
    generic_words,
)
from undercurrent.text.lexicon import stopwords
from undercurrent.text.terms import clean

OUT = Path(__file__).parents[1] / "src/undercurrent/text/intent_words/names_en.txt"
HEADER = """\
# Words the corpus usually capitalizes in the middle of a sentence: written in lowercase or
# at the start of a sentence, they still count as names for intents. Generated by
# bench/intent_names.py from {items:,} english comments and posts of the live database
# ({first} to {last} UTC): at least {min_items} items with the word in the middle of a
# sentence, capitalized in at least {share:.0%} of them.
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--min-items", type=int, default=5)
    parser.add_argument("--min-share", type=float, default=0.5)
    parser.add_argument("--min-authors", type=int, default=3)
    args = parser.parse_args()

    load_dotenv()
    client = connect(Env.from_environ())
    stop = stopwords("en")
    # german-only function words: german capitalizes every noun, its texts would make
    # "armut" a name
    german = stopwords("de") - stop
    excluded = stop | generic_words("en") | boundary_words("en")
    capitalized: Counter[str] = Counter()
    seen: Counter[str] = Counter()
    authors: dict[str, set[int]] = {}
    items = 0
    first = last = None
    with client.query_rows_stream(
        "SELECT created_at, author_hash, text FROM items FINAL WHERE lang = 'en'"
    ) as stream:
        for created_at, author, text in stream:
            if sum(word.lower() in german for word in _TOKEN.findall(text)) >= 2:
                continue
            items += 1
            first = min(first or created_at, created_at)
            last = max(last or created_at, created_at)
            words_in_item: dict[str, bool] = {}
            for sentence in _HARD_BREAK.split(clean(text)):
                words = [word.removesuffix("'s") for word in _TOKEN.findall(sentence)]
                if _case(words, stop, german) != CAPITALS:
                    continue
                for word in words[1:]:
                    if word.isupper() or not any(char.isalpha() for char in word):
                        continue
                    lower = word.lower()
                    upper = word[0].isupper() or any(char.isupper() for char in word[1:])
                    words_in_item[lower] = words_in_item.get(lower, False) or upper
            for word, upper in words_in_item.items():
                seen[word] += 1
                capitalized[word] += upper
                if upper:
                    authors.setdefault(word, set()).add(author)

    names = sorted(
        word
        for word, count in seen.items()
        if count >= args.min_items
        and capitalized[word] >= args.min_share * count
        and len(authors.get(word, ())) >= args.min_authors
        and word not in excluded
        and not any(char.isdigit() for char in word)
    )
    OUT.write_text(
        HEADER.format(
            items=items,
            first=f"{first:%Y-%m-%d %H:%M}",
            last=f"{last:%Y-%m-%d %H:%M}",
            min_items=args.min_items,
            share=args.min_share,
        )
        + "\n".join(names)
        + "\n",
        encoding="utf-8",
    )
    print(f"{len(names):,} names from {items:,} items -> {OUT}")


if __name__ == "__main__":
    main()
